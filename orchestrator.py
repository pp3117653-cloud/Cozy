"""Cozy's Architect -> Executor -> Auditor workflow. Standard library only."""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import time
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from connectors.app_connectors import DiscordConnector, FileConnector, SheetsConnector, WhatsAppConnector, retry

ROOT = Path(__file__).resolve().parent
STATE_PATH = ROOT / "workspace_state.json"


def now() -> str:
    return datetime.now(timezone.utc).isoformat()


def safe_id() -> str:
    return datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S") + "-" + uuid.uuid4().hex[:6]


def load_state() -> dict[str, Any]:
    if not STATE_PATH.exists():
        return {"version": 1, "updated_at": now(), "tasks": []}
    try:
        state = json.loads(STATE_PATH.read_text(encoding="utf-8"))
        if not isinstance(state, dict) or not isinstance(state.get("tasks", []), list):
            raise ValueError("invalid state shape")
        return state
    except (OSError, json.JSONDecodeError, ValueError):
        return {"version": 1, "updated_at": now(), "tasks": []}


def plan_task(prompt: str, mode: str, connectors: list[str]) -> dict[str, Any]:
    """Architect: create a transparent plan without requiring an LLM."""
    steps = ["analyze prompt", "record execution metadata"]
    if mode in {"full_team", "code_only"}:
        steps += ["prepare workspace response", "write execution report"]
    if mode in {"full_team", "notify_only"}:
        steps += [f"activate {name} connector" for name in connectors]
    return {"mode": mode, "connectors": connectors, "steps": steps, "strategy": "deterministic standard-library pipeline"}


def run_connector(name: str, task: dict[str, Any], summary: str) -> dict[str, Any]:
    if name == "whatsapp":
        return retry(lambda: WhatsAppConnector().send(summary))
    if name == "discord":
        return retry(lambda: DiscordConnector().send(summary, task["id"], task["status"]))
    if name in {"sheets", "google_sheets"}:
        record = {"task_id": task["id"], "prompt": task["prompt"], "status": task["status"], "mode": task["mode"], "timestamp": task["created_at"]}
        return retry(lambda: SheetsConnector().send(record))
    return {"skipped": True, "reason": f"Unknown connector: {name}"}


def execute(task: dict[str, Any], plan: dict[str, Any]) -> dict[str, Any]:
    """Executor: run selected connector actions while isolating failures."""
    task["status"] = "running"
    task["execution"] = {"started_at": now(), "connector_results": {}, "errors": []}
    summary = f"Task {task['id']} completed: {task['prompt']}"
    for name in plan["connectors"]:
        try:
            task["execution"]["connector_results"][name] = run_connector(name, task, summary)
        except Exception as exc:  # connector failures must not prevent the audit commit
            task["execution"]["errors"].append({"connector": name, "error": str(exc)[:500]})
    task["status"] = "completed" if not task["execution"]["errors"] else "completed_with_warnings"
    task["execution"]["finished_at"] = now()
    return task


def audit(task: dict[str, Any], plan: dict[str, Any]) -> dict[str, Any]:
    """Auditor: persist bounded state and produce a Markdown report."""
    errors = task.get("execution", {}).get("errors", [])
    report = "\n".join([
        f"# Cozy execution report — `{task['id']}`", "", f"- **Status:** {task['status']}", f"- **Mode:** {task['mode']}",
        f"- **Created:** {task['created_at']}", "", "## Prompt", "", task["prompt"], "", "## Architect plan", "", "\n".join(f"- {step}" for step in plan["steps"]),
        "", "## Connector results", "", "No connector errors." if not errors else "\n".join(f"- `{e['connector']}`: {e['error']}" for e in errors), "",
        "Generated by Cozy's standard-library GitHub Actions worker.",
    ])
    task["report"] = FileConnector(ROOT).write_report(task["id"], report)
    state = load_state()
    state["tasks"] = ([task] + state.get("tasks", []))[:100]
    state["updated_at"] = now()
    STATE_PATH.write_text(json.dumps(state, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return task


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--prompt", required=True)
    parser.add_argument("--mode", default="full_team", choices=["full_team", "code_only", "notify_only"])
    parser.add_argument("--connectors", default="", help="comma-separated connector names")
    args = parser.parse_args()
    prompt = re.sub(r"\s+", " ", args.prompt).strip()[:4000]
    if not prompt:
        print("Prompt cannot be empty", file=sys.stderr)
        return 2
    connectors = [x.strip() for x in args.connectors.split(",") if x.strip()]
    task = {"id": safe_id(), "prompt": prompt, "mode": args.mode, "created_at": now(), "status": "queued"}
    plan = plan_task(prompt, args.mode, connectors)
    try:
        task = execute(task, plan)
        task = audit(task, plan)
    except Exception as exc:
        task["status"] = "failed"
        task["error"] = str(exc)[:500]
        state = load_state(); state["tasks"] = ([task] + state.get("tasks", []))[:100]; state["updated_at"] = now(); STATE_PATH.write_text(json.dumps(state, indent=2) + "\n", encoding="utf-8")
        print(f"Task failed: {exc}", file=sys.stderr)
        return 1
    print(json.dumps(task, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
